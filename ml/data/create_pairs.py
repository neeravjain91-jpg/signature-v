def create_all_pairs():
    cfg = load_config()
    proc_dir = Path(cfg["paths"]["processed_dir"])
    pairs_dir = Path(cfg["paths"]["pairs_dir"])
    docs_dir = Path("docs")
    pairs_dir.mkdir(parents=True, exist_ok=True)
    docs_dir.mkdir(parents=True, exist_ok=True)

    seed = cfg["pairs"]["random_seed"]
    pair_cfg = cfg["pairs"]

    splits = ["train", "validation", "test"]
    stats = {}

    for split in splits:
        pairs = build_split_pairs(proc_dir, split, pair_cfg, seed=seed)
        csv_file = pairs_dir / f"{split}_pairs.csv"
        if pairs:
            with open(csv_file, "w", newline="", encoding="utf-8") as f:
                writer = csv.DictWriter(f, fieldnames=pairs[0].keys())
                writer.writeheader()
                writer.writerows(pairs)

        pos = sum(1 for p in pairs if p["label"] == 1)
        neg = sum(1 for p in pairs if p["label"] == 0)
        skilled = sum(1 for p in pairs if p["pair_type"] == "skilled_forgery")
        rnd = sum(1 for p in pairs if p["pair_type"] == "random_forgery")
        w_set = set(p["writer_1"] for p in pairs).union(set(p["writer_2"] for p in pairs))

        alias = "val" if split == "validation" else split
        stats[alias] = {
            "total_pairs": len(pairs),
            "pos_pairs": pos,
            "neg_pairs": neg,
            "balance_ratio": f"{pos / neg:.2f}" if neg > 0 else "N/A",
            "skilled_pairs": skilled,
            "random_pairs": rnd,
            "skilled_pct": round(skilled / neg * 100, 1) if neg > 0 else 0,
            "writers_count": len(w_set),
            "writers_range": f"{min(w_set)} - {max(w_set)}" if w_set else "None",
            "signatures_count": len(list((proc_dir / split / "genuine").glob("*.png"))) + len(list((proc_dir / split / "forged").glob("*.png")))
        }

    stats["total_writers"] = stats["train"]["writers_count"] + stats["val"]["writers_count"] + stats["test"]["writers_count"]
    stats["total_signatures"] = stats["train"]["signatures_count"] + stats["val"]["signatures_count"] + stats["test"]["signatures_count"]
    stats["total_pairs"] = stats["train"]["total_pairs"] + stats["val"]["total_pairs"] + stats["test"]["total_pairs"]
    stats["total_pos"] = stats["train"]["pos_pairs"] + stats["val"]["pos_pairs"] + stats["test"]["pos_pairs"]
    stats["total_neg"] = stats["train"]["neg_pairs"] + stats["val"]["neg_pairs"] + stats["test"]["neg_pairs"]
    stats["overall_balance"] = f"{stats['total_pos'] / stats['total_neg']:.2f}" if stats['total_neg'] > 0 else "N/A"

    generate_statistics_markdown(stats, docs_dir / "DATASET_STATISTICS.md")

    print("\n================ PAIR GENERATION COMPLETED ================")
    print(f"Train Pairs CSV      : {pairs_dir / 'train_pairs.csv'} ({stats['train']['total_pairs']} pairs)")
    print(f"Validation Pairs CSV : {pairs_dir / 'validation_pairs.csv'} ({stats['val']['total_pairs']} pairs)")
    print(f"Test Pairs CSV       : {pairs_dir / 'test_pairs.csv'} ({stats['test']['total_pairs']} pairs)")
    print(f"Overall Balance      : {stats['overall_balance']} (Total Pos: {stats['total_pos']}, Total Neg: {stats['total_neg']})")
    print(f"Documentation Saved  : {docs_dir / 'DATASET_STATISTICS.md'}")
    print("===========================================================\n")
    return True


if __name__ == "__main__":
    create_all_pairs()
