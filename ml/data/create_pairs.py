"""
Siamese Pair Generation Script.

Constructs reproducible positive and negative signature pairs for Siamese Network training/eval:
- Positive Pairs (label = 1): Genuine signature A vs Genuine signature B of writer i (i == j)
- Skilled Negative Pairs (label = 0): Genuine signature of writer i vs Skilled forgery targeting writer i
- Random Negative Pairs (label = 0): Genuine signature of writer i vs Genuine signature of writer j (i != j)

Operates strictly within individual splits (Train, Validation, Test) to guarantee zero data leakage.
Exports:
- data/pairs/train_pairs.csv
- data/pairs/validation_pairs.csv
- data/pairs/test_pairs.csv
- docs/DATASET_STATISTICS.md
"""

import os
import csv
import random
import itertools
from pathlib import Path
from collections import defaultdict
import yaml


def load_config(config_path: str = "ml/data/dataset_config.yaml") -> dict:
    with open(config_path, "r", encoding="utf-8") as f:
        return yaml.safe_load(f)


def build_split_pairs(proc_dir: Path, split_name: str, pair_cfg: dict, seed: int = 42):
    random.seed(seed)
    split_dir = proc_dir / split_name
    gen_dir = split_dir / "genuine"
    forg_dir = split_dir / "forged"

    gen_by_writer = defaultdict(list)
    forg_by_writer = defaultdict(list)

    for p in sorted(gen_dir.glob("*.png")):
        w_id = int(p.stem.split("_")[1])
        gen_by_writer[w_id].append(p)

    for p in sorted(forg_dir.glob("*.png")):
        w_id = int(p.stem.split("_")[1])
        forg_by_writer[w_id].append(p)

    writers = sorted(list(gen_by_writer.keys()))
    if not writers:
        return []

    if split_name == "train":
        p_count = pair_cfg["pairs_per_writer_train"]["positive_pairs_per_writer"]
        s_count = pair_cfg["pairs_per_writer_train"]["skilled_negative_pairs_per_writer"]
        r_count = pair_cfg["pairs_per_writer_train"]["random_negative_pairs_per_writer"]
    else:
        p_count = pair_cfg["pairs_per_writer_eval"]["positive_pairs_per_writer"]
        s_count = pair_cfg["pairs_per_writer_eval"]["skilled_negative_pairs_per_writer"]
        r_count = pair_cfg["pairs_per_writer_eval"]["random_negative_pairs_per_writer"]

    pairs = []

    for w_id in writers:
        g_list = gen_by_writer[w_id]
        f_list = forg_by_writer.get(w_id, [])

        # 1. Genuine-Genuine Positive Pairs (label = 1)
        all_possible_pos = list(itertools.combinations(g_list, 2))
        random.shuffle(all_possible_pos)
        chosen_pos = all_possible_pos[:p_count]
        for img1, img2 in chosen_pos:
            pairs.append({
                "image_1_path": str(img1).replace("\\", "/"),
                "image_2_path": str(img2).replace("\\", "/"),
                "label": 1,
                "pair_type": "genuine_genuine",
                "writer_1": w_id,
                "writer_2": w_id
            })

        # 2. Skilled Negative Pairs (label = 0: genuine vs skilled forgery)
        all_possible_skilled = list(itertools.product(g_list, f_list))
        random.shuffle(all_possible_skilled)
        chosen_skilled = all_possible_skilled[:s_count]
        for img1, img2 in chosen_skilled:
            pairs.append({
                "image_1_path": str(img1).replace("\\", "/"),
                "image_2_path": str(img2).replace("\\", "/"),
                "label": 0,
                "pair_type": "skilled_forgery",
                "writer_1": w_id,
                "writer_2": w_id
            })

        # 3. Random Negative Pairs (label = 0: genuine writer i vs genuine writer j, i != j)
        other_writers = [w for w in writers if w != w_id]
        chosen_random = []
        if other_writers:
            attempts = 0
            while len(chosen_random) < r_count and attempts < r_count * 10:
                attempts += 1
                w_other = random.choice(other_writers)
                img1 = random.choice(g_list)
                img2 = random.choice(gen_by_writer[w_other])
                pair_candidate = (img1, img2, w_id, w_other)
                if pair_candidate not in chosen_random:
                    chosen_random.append(pair_candidate)

        for img1, img2, w1, w2 in chosen_random:
            pairs.append({
                "image_1_path": str(img1).replace("\\", "/"),
                "image_2_path": str(img2).replace("\\", "/"),
                "label": 0,
                "pair_type": "random_forgery",
                "writer_1": w1,
                "writer_2": w2
            })

    random.shuffle(pairs)
    return pairs


